import 'package:warpgate_core/actions/action_spec.dart';
import 'package:warpgate_core/actions/registry/shapes.dart';

abstract final class SystemActionSpecs {
  static final List<ActionSpec> all = [
    ActionSpec(
      name: 'completion',
      cli: 'completion',
      title: 'Shell completions',
      summary: 'Print a completion script for your shell',
      permission: ActionPermission.read,
      args: [pos('shell', 'Shell', choices: ['bash', 'zsh', 'fish', 'powershell'])],
      examples: ['warpgate completion zsh > ~/.zfunc/_warpgate', 'source <(warpgate completion bash)'],
      text: '{script}',
      result: Shape.object({'script': Shape.string}),
    ),
    ActionSpec(
      name: 'doctor',
      cli: 'doctor',
      title: 'Check the install',
      summary: 'Check the install, PATH, secure storage, app and ssh-agent',
      permission: ActionPermission.read,
      args: [flag('perf', 'Also check memory, CPU, event loop latency and stalls of the running app')],
      examples: ['warpgate doctor', 'warpgate doctor --perf', 'warpgate doctor --json'],
      table: const TableSpec('checks', [TableColumn('ok', ''), TableColumn('name', 'CHECK'), TableColumn('detail', 'RESULT')]),
      result: Shape.object({'checks': Shape.list(Shapes.check), 'ok': Shape.boolean}),
    ),
    ActionSpec(
      name: 'diagnostics.export',
      cli: 'diagnostics export',
      title: 'Export diagnostics',
      summary: 'Save a performance and health report from the running app as JSON',
      permission: ActionPermission.read,
      args: [pos('file', 'File to write. Default: warpgate-diagnostics-<time>.json in the current folder', required: false)],
      examples: ['warpgate diagnostics export', 'warpgate diagnostics export report.json'],
      text: 'Saved {path}',
      result: Shape.object({'path': Shape.string, 'stalls': Shape.integer, 'rss_mb': Shape.integer}),
    ),
    ActionSpec(
      name: 'version',
      cli: 'version',
      title: 'Version',
      summary: 'Print the version',
      permission: ActionPermission.read,
      examples: ['warpgate version', 'warpgate version --json'],
      text: 'warpgate {version}',
      result: Shape.object({'version': Shape.string, 'schema_version': Shape.integer}),
    ),
    ActionSpec(
      name: 'help',
      cli: 'help',
      title: 'Help',
      summary: 'Show help for a command',
      permission: ActionPermission.read,
      args: [pos('command', 'Command', required: false, variadic: true, complete: CompletionKind.command)],
      examples: ['warpgate help', 'warpgate help cp', 'warpgate help hosts add'],
      result: Shape.object({'help': Shape.string}),
    ),
    ActionSpec(
      name: 'install',
      cli: 'install',
      title: 'Install the command',
      summary: 'Add warpgate to your PATH',
      permission: ActionPermission.write,
      examples: ['warpgate-cli --install', 'warpgate install'],
      text: 'Installed at {path}',
      result: Shape.object({'path': Shape.string, 'needs_new_shell': Shape.boolean}),
    ),
    ActionSpec(
      name: 'uninstall',
      cli: 'uninstall',
      title: 'Remove the command',
      summary: 'Remove warpgate from your PATH',
      permission: ActionPermission.destructive,
      confirm: 'Remove the warpgate command from your PATH?',
      examples: ['warpgate uninstall', 'warpgate uninstall --yes'],
      text: 'Removed',
      result: Shape.object({'removed': Shape.boolean}),
    ),
  ];
}
